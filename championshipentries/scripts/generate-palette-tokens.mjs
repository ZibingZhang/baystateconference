#!/usr/bin/env node
// Generates src/theme/generated/paletteTokens.ts from the color constants in
// the Jekyll site's Solarized and Rosé Pine skins, so the two projects never
// maintain separate copies of the same hex values. Runs automatically before
// `npm run dev` and `npm run build` (see package.json's predev/prebuild).
//
// Source of truth:
//   ../jekyll/_sass/skins/_solarized-runtime.scss
//   ../jekyll/_sass/skins/_rose-pine-runtime.scss

import { fileURLToPath } from "node:url";
import path from "node:path";
import fs from "node:fs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..", "..");
const skinsDir = path.join(repoRoot, "jekyll", "_sass", "skins");
const outFile = path.join(__dirname, "..", "src", "theme", "generated", "paletteTokens.ts");

function readSkin(filename) {
  const filePath = path.join(skinsDir, filename);
  if (!fs.existsSync(filePath)) {
    throw new Error(
      `Cannot find ${filePath}. This script expects the jekyll/ and championshipentries/ ` +
        `projects to be checked out as siblings in the same repo.`,
    );
  }
  return fs.readFileSync(filePath, "utf8");
}

// Extracts every `$prefix-some-name: #rrggbb;` declaration (ignores computed
// values like `mix(...)`, which aren't plain colors) and returns
// { someName: "#rrggbb" } with kebab-case names converted to camelCase.
function extractHexVars(source, prefix) {
  const pattern = new RegExp(`\\$${prefix}-([a-z0-9-]+):\\s*(#[0-9a-fA-F]{6})\\s*;`, "g");
  const result = {};
  for (const match of source.matchAll(pattern)) {
    const [, kebabName, hex] = match;
    const camelName = kebabName.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
    result[camelName] = hex.toLowerCase();
  }
  return result;
}

// Replicates Sass's `mix($color1, $color2, 50%)`: a simple per-channel
// average. Used to derive the same divider shade the Jekyll skin computes
// as `mix($sol-base1, $sol-base3)` / `mix($sol-base01, $sol-base03)`,
// without duplicating a hardcoded hex for it.
function mix(hexA, hexB) {
  const a = parseInt(hexA.slice(1), 16);
  const b = parseInt(hexB.slice(1), 16);
  const channel = (shift) => {
    const ca = (a >> shift) & 0xff;
    const cb = (b >> shift) & 0xff;
    return Math.round((ca + cb) / 2);
  };
  const r = channel(16);
  const g = channel(8);
  const bl = channel(0);
  return `#${[r, g, bl].map((c) => c.toString(16).padStart(2, "0")).join("")}`;
}

const solarizedSource = readSkin("_solarized-runtime.scss");
const solarizedBase = extractHexVars(solarizedSource, "sol");
const solarizedTokens = {
  ...solarizedBase,
  dividerLight: mix(solarizedBase.base1, solarizedBase.base3),
  dividerDark: mix(solarizedBase.base01, solarizedBase.base03),
};

const rosePineSource = readSkin("_rose-pine-runtime.scss");
const rosePineAll = extractHexVars(rosePineSource, "rp");
const rosePineTokens = { dawn: {}, moon: {} };
for (const [name, hex] of Object.entries(rosePineAll)) {
  if (name.startsWith("dawn")) {
    const key = name[4].toLowerCase() + name.slice(5);
    rosePineTokens.dawn[key] = hex;
  } else if (name.startsWith("moon")) {
    const key = name[4].toLowerCase() + name.slice(5);
    rosePineTokens.moon[key] = hex;
  }
}

const header = `// AUTO-GENERATED by scripts/generate-palette-tokens.mjs - do not edit by hand.
// Regenerated automatically by \`npm run dev\` / \`npm run build\` (see predev/prebuild
// in package.json). Source of truth:
//   jekyll/_sass/skins/_solarized-runtime.scss
//   jekyll/_sass/skins/_rose-pine-runtime.scss
`;

const body = `
export const solarizedTokens = ${JSON.stringify(solarizedTokens, null, 2)} as const;

export const rosePineTokens = ${JSON.stringify(rosePineTokens, null, 2)} as const;
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, header + body);
console.log(`Wrote ${path.relative(repoRoot, outFile)}`);
